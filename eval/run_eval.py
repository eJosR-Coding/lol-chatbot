"""Retrieval evaluation for the LoL RAG chatbot (no LLM involved).

Runs the retriever from backend/rag.py on eval/questions.json and reports, per
question, the top KB entry, cosine score, accept/reject at the app's context
threshold (backend.app.WEAK_MATCH_THRESHOLD) and correctness, followed by
summary metrics and a threshold sweep.

Usage (from the repository root):
    uv run python eval/run_eval.py                 # print the report
    uv run python eval/run_eval.py --e2e --write   # + 5 /chat samples (needs Ollama), rewrite eval/results.md

Thresholds are only reported, never tuned. Text after the line
"<!-- manual-notes -->" in an existing eval/results.md is preserved on rewrite.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.app import WEAK_MATCH_THRESHOLD  # noqa: E402
from backend.kb import KNOWLEDGE_BASE  # noqa: E402
from backend.rag import MODEL_NAME, LolRetriever  # noqa: E402

QUESTIONS = ROOT / "eval" / "questions.json"
RESULTS = ROOT / "eval" / "results.md"
MARKER = "<!-- manual-notes -->"
SWEEP = [round(0.30 + 0.05 * i, 2) for i in range(7)]  # 0.30 .. 0.60

# Questions used for the optional end-to-end /chat samples.
E2E_SAMPLES = [
    "¿Qué es el Barón?",  # (a) correct retrieval
    "¿Qué es el daño explosivo en un solo combo?",  # (a) correct retrieval
    "¿Para qué sirve el hechizo de invocador que te teletransporta unos metros?",  # (a) wrong retrieval
    "¿Cuál es la habilidad pasiva de Ahri?",  # (b) not in KB, accepted at 0.45
    "¿Cómo preparo una tortilla de papas?",  # (c) out of domain
]


def load_rows(retriever: LolRetriever) -> list[dict]:
    data = json.loads(QUESTIONS.read_text(encoding="utf-8"))
    ids = {qa["pregunta"]: i + 1 for i, qa in enumerate(KNOWLEDGE_BASE)}
    rows = []
    for group in ("in_domain", "uncovered", "out_of_domain"):
        for item in data[group]:
            res = retriever.retrieve(item["q"])
            expected = [ids[e] for e in item.get("expected_questions", [])]
            rows.append(
                {
                    "group": group,
                    "q": item["q"],
                    "expected": expected,
                    "top_id": ids[res["matched_question"]],
                    "top_question": res["matched_question"],
                    "score": res["score"],
                }
            )
    return rows


def top1_correct(row: dict) -> bool:
    return row["top_id"] in row["expected"]


def accepted(row: dict, threshold: float) -> bool:
    return row["score"] >= threshold


def is_correct(row: dict, threshold: float) -> bool:
    if row["group"] == "in_domain":
        return top1_correct(row) and accepted(row, threshold)
    return not accepted(row, threshold)  # correct = rejected


def pct(num: int, den: int) -> str:
    return f"{num}/{den} ({100 * num / den:.0f}%)"


def metrics(rows: list[dict], threshold: float) -> dict:
    a = [r for r in rows if r["group"] == "in_domain"]
    b = [r for r in rows if r["group"] == "uncovered"]
    c = [r for r in rows if r["group"] == "out_of_domain"]
    return {
        "top1": sum(top1_correct(r) for r in a),
        "acc": sum(is_correct(r, threshold) for r in a),
        "a_n": len(a),
        "rej_b": sum(not accepted(r, threshold) for r in b),
        "b_n": len(b),
        "rej_c": sum(not accepted(r, threshold) for r in c),
        "c_n": len(c),
    }


def md_escape(text: str) -> str:
    return text.replace("|", "\\|")


def exact_match_sanity(retriever: LolRetriever) -> int:
    """Sanity check: querying with each KB question verbatim should return itself."""
    return sum(
        retriever.retrieve(qa["pregunta"])["matched_question"] == qa["pregunta"]
        for qa in KNOWLEDGE_BASE
    )


def render(rows: list[dict], e2e: list[dict] | None, sanity: int) -> str:
    t = WEAK_MATCH_THRESHOLD
    m = metrics(rows, t)
    labels = {
        "in_domain": "(a) In KB",
        "uncovered": "(b) League, not in KB",
        "out_of_domain": "(c) Out of domain",
    }
    out = [
        "# Retrieval evaluation results",
        "",
        "Generated by `eval/run_eval.py` (retriever only, no LLM). "
        f"Embedding model: `{MODEL_NAME}`; KB entries: {len(KNOWLEDGE_BASE)}; "
        f"questions: {len(rows)}; context threshold: {t} "
        "(`WEAK_MATCH_THRESHOLD` in `backend/app.py`).",
        "",
        "Every question is evaluated as the first turn of a conversation (no history), "
        "so only the message-alone retrieval path is exercised. "
        "`accepted` means score >= threshold, i.e. the retrieved entry would be passed to the LLM as context.",
        "",
        "Note on what \"rejected\" means in the running app: the retriever's own threshold (0.30) "
        "is the only hard refusal (\"No entendí esa...\", first turn only). Between 0.30 and "
        f"{t} the app drops the KB context but still calls the LLM, which then answers from its own "
        "weights. The tables below measure the {t} context gate; the 0.30 row of the sweep "
        "approximates hard refusals.".replace("{t}", str(t)),
        "",
        "## Summary",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| (a) Top-1 is the expected entry (ignoring threshold) | {pct(m['top1'], m['a_n'])} |",
        f"| (a) Retrieval accuracy: top-1 correct and accepted at {t} | {pct(m['acc'], m['a_n'])} |",
        f"| (b) Correct rejection of League questions not in the KB | {pct(m['rej_b'], m['b_n'])} |",
        f"| (c) Correct rejection of out-of-domain questions | {pct(m['rej_c'], m['c_n'])} |",
        f"| Sanity: verbatim KB question returns itself as top-1 | {pct(sanity, len(KNOWLEDGE_BASE))} |",
        "",
        "## Threshold sweep",
        "",
        "Accuracy = (a) questions whose top-1 is correct and whose score passes the threshold. "
        "Rejection = questions in (b)/(c) whose score falls below the threshold. "
        f"The app uses {t}; the sweep only reports the trade-off.",
        "",
        "| Threshold | (a) accuracy | (b) rejected | (c) rejected |",
        "|---|---|---|---|",
    ]
    for th in SWEEP:
        s = metrics(rows, th)
        mark = " (app)" if abs(th - t) < 1e-9 else ""
        out.append(
            f"| {th:.2f}{mark} | {pct(s['acc'], s['a_n'])} | "
            f"{pct(s['rej_b'], s['b_n'])} | {pct(s['rej_c'], s['c_n'])} |"
        )
    out += [
        "",
        f"## Per-question results (threshold {t})",
        "",
        "| Group | Question | Top entry (#id) | Score | Decision | Correct |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        decision = "accepted" if accepted(r, t) else "rejected"
        ok = "yes" if is_correct(r, t) else "NO"
        top = f"{md_escape(r['top_question'])} (#{r['top_id']:03d})"
        if r["group"] == "in_domain" and not top1_correct(r):
            exp = ", ".join(f"#{i:03d}" for i in r["expected"])
            top += f" [expected {exp}]"
        out.append(
            f"| {labels[r['group']]} | {md_escape(r['q'])} | {top} | "
            f"{r['score']:.3f} | {decision} | {ok} |"
        )
    if e2e:
        out += [
            "",
            "## End-to-end samples (`/chat`, Ollama `qwen2.5:0.5b`)",
            "",
            "Raw replies from one run; generation is stochastic (temperature 0.3), so wording varies between runs.",
            "",
        ]
        for s in e2e:
            out += [
                f"**Q:** {s['q']}",
                "",
                f"- Retrieved: {s['matched_question']} (score {s['score']:.3f}, used_context={s['used_context']})",
                f"- KB answer: {s['matched_answer']}",
                f"- Reply: {s['reply']}",
                "",
            ]
    out += ["", MARKER, ""]
    return "\n".join(out)


def run_e2e() -> list[dict] | None:
    import httpx
    from fastapi.testclient import TestClient

    from backend.app import OLLAMA_HOST, app

    try:
        httpx.get(f"{OLLAMA_HOST}/api/tags", timeout=2).raise_for_status()
    except httpx.HTTPError:
        print("Ollama not reachable; skipping end-to-end samples.", file=sys.stderr)
        return None
    samples = []
    with TestClient(app) as client:  # runs the real app code, no server needed
        for q in E2E_SAMPLES:
            data = client.post("/chat", json={"message": q, "history": []}).json()
            samples.append({"q": q, **data})
    return samples


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true", help="write the report to eval/results.md")
    ap.add_argument("--e2e", action="store_true", help="also run 5 /chat samples (needs Ollama)")
    args = ap.parse_args()

    retriever = LolRetriever()
    rows = load_rows(retriever)
    sanity = exact_match_sanity(retriever)
    e2e = run_e2e() if args.e2e else None
    report = render(rows, e2e, sanity)
    print(report)
    if not args.write:
        return
    if RESULTS.exists() and MARKER in RESULTS.read_text(encoding="utf-8"):
        manual = RESULTS.read_text(encoding="utf-8").split(MARKER, 1)[1]
        report = report.rstrip("\n").removesuffix(MARKER).rstrip("\n") + f"\n\n{MARKER}{manual}"
    RESULTS.write_text(report, encoding="utf-8")


if __name__ == "__main__":
    main()
